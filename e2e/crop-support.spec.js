import { test, expect } from '@playwright/test'

test('Owner season journal → Admin assignment → Engineer advice → follow-up → closure → review → reopen', async ({ browser, request }) => {
  const api = process.env.E2E_API_URL
  if (api !== 'http://127.0.0.1:5189' || !process.env.TEST_POSTGRES_CONNECTION) throw new Error('Use the disposable PostgreSQL browser harness.')
  const password = process.env.SEED_ADMIN_PASSWORD
  async function post(path, body, token) {
    const response = await request.post(`${api}${path}`, { data: body, headers: token ? { Authorization: `Bearer ${token}` } : {} })
    expect(response.ok(), `${path}: ${response.status()}`).toBeTruthy()
    return (await response.json()).data
  }
  // The disposable database includes the explicitly retained sample-admin migration.
  const admin = await post('/api/auth/login', { email: 'admin@sep.local', password: '123456' })
  const owner = await post('/api/users', { email: 'browser-owner@example.com', fullName: 'Browser Owner', password, roles: ['FarmOwner'] }, admin.accessToken)
  const assigned = await post('/api/users', { email: 'browser-engineer@example.com', fullName: 'Browser Engineer', password, roles: ['FarmEngineer'] }, admin.accessToken)
  const farm = await post('/api/farms', { name: 'Browser rice farm' }, admin.accessToken)
  await post(`/api/farms/${farm.id}/members`, { userId: owner.id }, admin.accessToken)
  async function login(email, loginPassword = password) {
    const context = await browser.newContext({ baseURL: 'http://127.0.0.1:5179' })
    const page = await context.newPage()
    await page.goto('/dang-nhap')
    await page.getByLabel('Email', { exact: true }).fill(email)
    await page.locator('input[name="password"]').fill(loginPassword)
    await page.locator('button[type="submit"]').click()
    await expect(page).toHaveURL(/\/app/)
    await page.getByRole('link', { name: 'Crop support', exact: true }).click()
    return { context, page }
  }
  const ownerUi = await login(owner.email)
  const engineerUi = await login('browser-engineer@example.com')
  const adminUi = await login('admin@sep.local', '123456')
  try {
    const page = ownerUi.page
    await page.getByRole('link', { name: 'Crop seasons', exact: true }).click()
    await page.getByRole('button', { name: 'Create season', exact: true }).click()
    await page.getByRole('combobox', { name: 'Farm', exact: true }).selectOption(String(farm.id))
    await page.getByLabel('Season name', { exact: true }).fill('Browser autumn')
    await page.getByLabel('Crop', { exact: true }).fill('Rice')
    await page.getByRole('button', { name: 'Save season', exact: true }).click()
    await page.getByRole('button', { name: 'Record activity', exact: true }).click()
    await page.getByLabel('Activity date').fill(new Date().toISOString().slice(0, 10))
    await page.getByLabel('Activity type').selectOption('INSPECTION')
    await page.getByLabel('Description', { exact: true }).fill('Journal inspection before crop report')
    await page.getByRole('button', { name: 'Save activity', exact: true }).click()
    await page.getByRole('button', { name: 'Report abnormal crop condition' }).click()
    await expect(page.getByLabel('Crop', { exact: true })).toHaveValue('Rice')
    await page.getByLabel('Observed at (local time)').fill(new Date(Date.now() - 3600000).toISOString().slice(0, 16))
    await page.getByLabel('Symptoms', { exact: true }).fill('Yellow leaves observed this morning')
    await page.getByRole('button', { name: 'Submit crop report', exact: true }).click()
    await expect(page.getByRole('heading', { name: /Crop report #/ })).toBeVisible()
    const heading = await page.getByRole('heading', { name: /Crop report #/ }).innerText()
    const id = Number(heading.match(/#(\d+)/)[1])
    const adminPage = adminUi.page
    await adminPage.reload()
    await adminPage.getByRole('button', { name: `Open crop report #${id}` }).click()
    await adminPage.getByLabel('Responsible engineer').selectOption(String(assigned.id))
    await adminPage.getByRole('button', { name: 'Assign engineer', exact: true }).click()
    await expect(adminPage.getByText('ASSIGNED', { exact: true })).toBeVisible()
    const engineer = engineerUi.page
    await engineer.reload()
    await engineer.getByRole('button', { name: `Open crop report #${id}` }).click()
    await expect(engineer.getByText('Journal inspection before crop report', { exact: true })).toBeVisible()
    await engineer.getByLabel('Consultation note').fill('Please describe irrigation')
    await engineer.getByRole('button', { name: 'Request additional information' }).click()
    await expect(engineer.getByText('INFORMATION_REQUESTED', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Reload report' }).click()
    await page.getByLabel('Consultation note').fill('Watered yesterday')
    await page.getByRole('button', { name: 'Send additional information' }).click()
    await expect(page.getByLabel('Consultation note')).toHaveCount(0)
    await engineer.getByRole('button', { name: 'Reload report' }).click()
    await engineer.getByLabel('Consultation note').fill('Inspect roots and adjust irrigation after inspection')
    await engineer.getByLabel('Recommend an on-site survey').check()
    await engineer.getByRole('button', { name: 'Record recommendation' }).click()
    await expect(engineer.getByText('On-site survey recommended.', { exact: true })).toBeVisible()
    await engineer.getByLabel('Consultation note').fill('Advice provided; case resolved')
    await page.getByRole('button', { name: 'Reload report' }).click()
    await page.getByLabel('Feedback type').selectOption('ACTION_TAKEN')
    await page.getByLabel('Consultation note').fill('Performed follow-up care')
    await page.getByLabel('Linked care activity (optional)').selectOption({ index: 1 })
    await page.getByRole('button', { name: 'Send follow-up', exact: true }).click()
    await expect(page.getByText('Performed follow-up care', { exact: true })).toBeVisible()
    const conflict = engineer.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/api/crop-condition-reports/${id}/resolve`))
    await engineer.getByRole('button', { name: 'Resolve report' }).click()
    expect((await conflict).status()).toBe(409)
    await expect(engineer.getByLabel('Consultation note')).toHaveValue('Advice provided; case resolved')
    await engineer.getByRole('button', { name: 'Reload report' }).click()
    await expect(engineer.getByRole('button', { name: 'Use latest revision for this draft' })).toBeVisible()
    await expect(engineer.getByLabel('Consultation note')).toHaveValue('Advice provided; case resolved')
    await expect(engineer.getByRole('button', { name: 'Resolve report' })).toBeDisabled()
    await engineer.getByRole('button', { name: 'Use latest revision for this draft' }).click()
    await engineer.getByRole('button', { name: 'Resolve report' }).click()
    await expect(engineer.getByRole('button', { name: 'Reopen report with reason' })).toBeVisible()
    await page.getByRole('button', { name: 'Reload report' }).click()
    await expect(page.getByText('Advice provided; case resolved', { exact: true })).toBeVisible()
    await expect(page.getByText('Watered yesterday', { exact: true })).toBeVisible()
    await page.getByLabel('Consultation note').fill('Still no improvement')
    await page.getByRole('button', { name: 'Report no improvement / request review' }).click()
    await expect(page.getByText('REVIEW_REQUESTED', { exact: true })).toBeVisible()
    await engineer.getByRole('button', { name: 'Reload report' }).click()
    await engineer.getByLabel('Consultation note').fill('Reopening to review continued symptoms')
    await engineer.getByRole('button', { name: 'Reopen report with reason' }).click()
    await expect(engineer.getByRole('button', { name: 'Record recommendation' })).toBeVisible()
    const ownerAuth = await post('/api/auth/login', { email: owner.email, password })
    const detailResponse = await request.get(`${api}/api/crop-condition-reports/${id}`, { headers: { Authorization: `Bearer ${ownerAuth.accessToken}` } })
    const detail = (await detailResponse.json()).data
    expect(detail.status).toBe('IN_REVIEW')
    const seasonResponse = await request.get(`${api}/api/crop-seasons/${detail.cropSeasonId}`, { headers: { Authorization: `Bearer ${ownerAuth.accessToken}` } })
    const season = (await seasonResponse.json()).data
    expect(season.status).toBe('ACTIVE'); expect(season.revision).toBe(2)
    const swagger = await (await request.get(`${api}/swagger/v1/swagger.json`)).json()
    expect(swagger.paths['/api/crop-condition-reports/{id}/follow-ups'].post.description).toContain('NOT_IMPROVED')
    await page.reload()
    await page.getByRole('button', { name: 'Notifications, unread notifications', exact: true }).click()
    const notifications = page.getByRole('region', { name: 'Notifications', exact: true })
    await expect(notifications.getByRole('listitem').first()).toBeVisible()
    const read = page.waitForResponse(response => response.request().method() === 'PATCH' && /\/api\/notifications\/\d+\/read$/.test(response.url()))
    await notifications.getByRole('button', { name: 'Mark as read', exact: true }).first().click()
    expect((await read).ok()).toBeTruthy()
    await expect(notifications.getByRole('button', { name: 'Read all', exact: true })).toBeEnabled()
    await notifications.getByRole('button', { name: 'Read all', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Notifications', exact: true })).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Notifications', exact: true }).click()
    await expect(notifications.getByRole('button', { name: 'Read all', exact: true })).toBeDisabled()
    await expect(notifications.getByRole('button', { name: 'Mark as read', exact: true })).toHaveCount(0)
  } finally { await ownerUi.context.close(); await engineerUi.context.close(); await adminUi.context.close() }
})

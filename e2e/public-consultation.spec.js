import { submitInstallation } from './submit-installation'
import { expect, test } from '@playwright/test'

test.use({ actionTimeout: 15000 })

test('consultation reaches active rental and the assigned device is repaired', async ({ page: admin, browser, request }) => {
  test.setTimeout(300000) // Includes one real maintenance recurrence.
  if (process.env.E2E_API_URL !== 'http://127.0.0.1:5189' || !process.env.TEST_POSTGRES_CONNECTION) throw new Error('Use the disposable PostgreSQL harness.')
  await admin.goto('/dang-nhap')
  await admin.getByLabel('Email', { exact: true }).fill('admin@sep.local')
  await admin.locator('input[name=password]').fill('123456')
  await admin.locator('button[type=submit]').click()
  const search = admin.getByRole('searchbox', { name: 'Search workspace pages' })
  await search.fill('no-such-page-908')
  await expect(admin.getByText('No results found.', { exact: true })).toBeVisible()
  await search.press('Escape')
  await admin.getByRole('button', { name: /^Account:/ }).click()
  await admin.getByRole('link', { name: 'Nội dung trang chủ' }).click()
  const title = 'Cảm biến độ ẩm vườn'
  await admin.getByRole('button', { name: '＋ Tạo nội dung' }).click()
  await admin.getByRole('combobox', { name: 'Danh mục' }).selectOption('DEVICE')
  await admin.getByLabel('Tiêu đề').fill(title)
  await admin.getByLabel('Nội dung', { exact: true }).fill('Theo dõi độ ẩm đất tại vùng rễ.')
  await admin.getByLabel(/Giá thuê mỗi tháng/).fill('35000')
  await admin.getByRole('button', { name: 'Lưu nội dung' }).click()
  const publish = admin.getByRole('button', { name: 'Xuất bản ' + title, exact: true })
  await expect(publish).toBeVisible()
  const guest = await browser.newContext({ baseURL: 'http://127.0.0.1:5179' })
  try {
    const page = await guest.newPage()
    // The public homepage embeds external decorative media. Exercise local product requests only.
    await page.route(/^https:\/\//, route => route.abort())
    await page.goto('/')
    const empty = page.getByText(/Chưa có thông tin được công bố/)
    await expect(empty).toBeVisible()
    await publish.click()
    const unpublish = admin.getByRole('button', { name: 'Gỡ xuất bản ' + title })
    await expect(unpublish).toBeVisible()
    await page.reload()
    const listing = page.getByRole('region', { name: 'Thiết bị, dịch vụ và chính sách thuê' })
    await expect(listing.getByRole('heading', { name: title })).toBeVisible()
    await expect(listing.getByText(/35\.000/)).toBeVisible()
    await listing.getByRole('link', { name: 'Tư vấn thiết bị' }).click()
    await page.getByRole('button', { name: 'Gửi yêu cầu tư vấn' }).click()
    await expect(page.getByLabel('Họ tên')).toHaveJSProperty('validationMessage', 'The customer name field is required.')
    await page.getByLabel('Số điện thoại').fill('abc123')
    await page.getByLabel('Email (không bắt buộc)').fill('invalid')
    await page.getByRole('button', { name: 'Gửi yêu cầu tư vấn' }).click()
    await expect(page.getByLabel('Số điện thoại')).toHaveJSProperty('validationMessage', 'Invalid phone format.')
    await expect(page.getByLabel('Email (không bắt buộc)')).toHaveJSProperty('validationMessage', 'Invalid email format.')
    await page.getByLabel('Email (không bắt buộc)').fill('')
    await page.getByLabel('Họ tên').fill('Khách tư vấn')
    await page.getByLabel('Hình thức tư vấn').selectOption('ONLINE')
    await page.getByLabel('Số điện thoại').fill('0901234567')
    await page.getByLabel('Vị trí nông trại').fill('Đồng Tháp')
    await page.getByLabel('Nhu cầu dịch vụ').fill('Thuê cảm biến độ ẩm')
    await page.getByLabel('Nội dung tư vấn').fill('Cần tư vấn lắp đặt cảm biến cho vườn.')
    await page.getByRole('button', { name: 'Gửi yêu cầu tư vấn' }).click()
    await expect(page.getByText(/Đã tiếp nhận yêu cầu #\d+/)).toBeVisible()
    const receipt = await page.getByText(/Đã tiếp nhận yêu cầu #\d+/).innerText()
    const consultationId = Number(receipt.match(/#(\d+)/)[1])
    await unpublish.click()
    await expect(publish).toBeVisible()
    await page.goto('/')
    await expect(empty).toBeVisible()
    await expect(listing.getByRole('heading', { name: title })).toHaveCount(0)
    await submitInstallation(browser, request, admin, consultationId)
  } finally { await guest.close() }
})

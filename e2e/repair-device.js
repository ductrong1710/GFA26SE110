import { expect } from '@playwright/test'

export async function repairDevice(owner, admin, technician, contractId, uav, technicianId) {
  await owner.getByRole('combobox', { name: 'Rental contract' }).selectOption(String(contractId))
  await owner.getByRole('combobox', { name: 'Assigned device' }).selectOption({ label: uav.code + ' · ' + uav.name + ' · Orchard dock' })
  await owner.getByLabel('Incident description').fill('Dock connector intermittently loses power.')
  await owner.getByRole('button', { name: 'Report incident' }).click()
  const heading = await owner.getByRole('heading', { name: /Device incident #\d+/ }).innerText()
  const incidentId = Number(heading.match(/#(\d+)/)[1])
  const incidentButton = 'Open incident #' + incidentId
  await admin.getByRole('link', { name: 'Device incidents', exact: true }).click()
  await admin.getByRole('button', { name: incidentButton, exact: true }).click()
  await admin.getByRole('combobox', { name: 'Service type' }).selectOption('REPAIR')
  await admin.getByRole('combobox', { name: 'Technician' }).selectOption(String(technicianId))
  const day = new Date(Date.now() + 2 * 86400000).toISOString().slice(0, 10)
  await admin.getByLabel('Appointment').fill(day + 'T10:00')
  await admin.getByLabel('Assignment note').fill('Inspect dock power connector.')
  await admin.getByRole('button', { name: 'Create service job' }).click()
  const receipt = await admin.getByText(/Service job #\d+ created/).innerText()
  const jobId = Number(receipt.match(/#(\d+)/)[1])
  await admin.getByRole('button', { name: incidentButton, exact: true }).click()
  await expect(admin.getByRole('link', { name: 'View service job #' + jobId })).toBeVisible()
  await expect(admin.getByRole('button', { name: 'Create service job' })).toHaveCount(0)
  async function openJob(page) {
    await page.getByRole('link', { name: 'Service jobs', exact: true }).click()
    await page.getByRole('button', { name: 'Open service job #' + jobId, exact: true }).click()
  }
  await openJob(technician)
  await technician.getByRole('button', { name: 'Start service work' }).click()
  const report = technician.getByRole('region', { name: 'Technician service report' })
  await report.getByLabel('Cause', { exact: true }).fill('Loose terminal at dock')
  await report.getByLabel('Work performed').fill('Reseated the terminal and secured the cable')
  await report.getByLabel('Components used').fill('None')
  await report.getByLabel('Test results').fill('Stable power and connection throughout test')
  await report.getByLabel('Notes', { exact: true }).fill('Handed back to owner for operational check')
  for (const name of ['Connectivity', 'Operation']) await report.getByRole('combobox', { name }).selectOption('true')
  await report.getByRole('button', { name: 'Submit service report' }).click()
  const revision = 'View report revision 1'
  await expect(technician.getByRole('button', { name: revision })).toBeVisible()
  await openJob(owner)
  await owner.getByRole('button', { name: revision }).click()
  await owner.getByLabel('Decision note').fill('Dock is working again')
  await owner.getByRole('button', { name: 'Confirm operation' }).click()
  await expect(owner.getByText('Service decision recorded.')).toBeVisible()
  await openJob(admin)
  await admin.getByRole('button', { name: revision }).click()
  await admin.getByLabel('Decision note').fill('Verified successful tests and owner confirmation')
  await admin.getByRole('button', { name: 'Approve service result' }).click()
  await expect(admin.getByRole('region', { name: 'Service job #' + jobId, exact: true }).getByText('Closed', { exact: true })).toBeVisible()
  await owner.getByRole('link', { name: 'Device incidents', exact: true }).click()
  await owner.getByRole('button', { name: incidentButton, exact: true }).click()
  await expect(owner.getByRole('region', { name: heading, exact: true }).getByText('Resolved', { exact: true })).toBeVisible()
}
